// Writes schemas/query-engine.d.ts, the TypeScript types for the published JSON Schemas
// (plan format, catalogue format, API bodies). Run `npm run types` after changing a schema;
// a test fails while the committed file is out of date.
//
// It handles only the JSON Schema keywords the engine's schemas use, and stops on any other,
// so a schema change that needs more is noticed rather than mistyped.

import { writeFileSync } from 'node:fs';
import { CATALOGUE_VERSION, PLAN_VERSION, SCHEMA_FILES, readSchema, type JsonSchema } from '../src/schemas.ts';
import { engineVersion } from '../src/version.ts';

export const TYPES_FILE = new URL('../schemas/query-engine.d.ts', import.meta.url);

// Keywords that constrain values but not their TypeScript type.
const IGNORED = new Set([
  '$schema', '$id', '$defs', 'title', 'description', 'minimum', 'maximum', 'minItems', 'maxItems',
  'minLength', 'pattern', 'additionalProperties', 'required',
]);
const HANDLED = new Set(['$ref', 'const', 'enum', 'oneOf', 'type', 'properties', 'items', 'prefixItems']);

interface Named {
  name: string;
  schema: JsonSchema;
  file: string;
}

export function generateTypes(): string {
  const schemas = SCHEMA_FILES.map((file) => ({ file, schema: readSchema(file) }));
  const rootNames = new Map<string, string>();
  const named: Named[] = [];
  for (const { file, schema } of schemas) {
    const id = schema['$id'] as string;
    const isType = HANDLED_ROOT.some((keyword) => keyword in schema);
    if (isType) {
      rootNames.set(id, schema['title'] as string);
      named.push({ name: schema['title'] as string, schema, file });
    }
    for (const [name, definition] of Object.entries((schema['$defs'] ?? {}) as Record<string, JsonSchema>)) {
      named.push({ name, schema: definition, file });
    }
  }
  const seen = new Set<string>();
  for (const { name, file } of named) {
    if (seen.has(name)) throw new Error(`${file}: the type name ${name} is used twice across the schemas`);
    seen.add(name);
  }

  const resolveRef = (ref: string): string => {
    const [base, fragment] = ref.split('#');
    if (fragment === undefined || fragment === '') {
      const name = rootNames.get(base as string);
      if (name === undefined) throw new Error(`Unknown $ref ${ref}`);
      return name;
    }
    const match = /^\/\$defs\/([A-Za-z0-9]+)$/.exec(fragment);
    if (match === null) throw new Error(`Unsupported $ref ${ref}`);
    return match[1] as string;
  };

  const lines = [
    '// Generated by `npm run types` from schemas/*.schema.json. Do not edit by hand.',
    `// ccrp-query-engine ${engineVersion()}: plan format ${PLAN_VERSION}, catalogue format ${CATALOGUE_VERSION}, API v1.`,
    '// Licence: GPL-3.0-only. See docs/api-reference.md.',
    '',
  ];
  for (const { name, schema, file } of named) {
    const at = `${file} ${name}`;
    lines.push(...comment(schema['description'], ''));
    if (schema['type'] === 'object' && schema['properties'] !== undefined) {
      lines.push(`export interface ${name} ${objectType(schema, resolveRef, at, '')}`, '');
    } else {
      lines.push(`export type ${name} = ${typeOf(schema, resolveRef, at, '')};`, '');
    }
  }
  return lines.join('\n');
}

const HANDLED_ROOT = ['type', 'oneOf', '$ref', 'enum', 'const'];

function typeOf(schema: JsonSchema, resolveRef: (ref: string) => string, at: string, indent: string): string {
  for (const keyword of Object.keys(schema)) {
    if (!IGNORED.has(keyword) && !HANDLED.has(keyword)) {
      throw new Error(`${at}: the type generator does not handle the keyword ${keyword}`);
    }
  }
  if (typeof schema['$ref'] === 'string') return resolveRef(schema['$ref']);
  if ('const' in schema) return JSON.stringify(schema['const']);
  if (Array.isArray(schema['enum'])) return schema['enum'].map((value) => JSON.stringify(value)).join(' | ');
  if (Array.isArray(schema['oneOf'])) {
    return (schema['oneOf'] as JsonSchema[]).map((member) => typeOf(member, resolveRef, at, indent)).join(' | ');
  }
  const type = schema['type'];
  if (Array.isArray(type)) return type.map((member) => primitive(member as string, at)).join(' | ');
  if (type === 'object') return objectType(schema, resolveRef, at, indent);
  if (type === 'array') {
    if (Array.isArray(schema['prefixItems'])) {
      if (schema['items'] !== false) throw new Error(`${at}: a tuple needs "items": false`);
      const members = (schema['prefixItems'] as JsonSchema[]).map((member) => typeOf(member, resolveRef, at, indent));
      return `[${members.join(', ')}]`;
    }
    const items = schema['items'];
    if (typeof items !== 'object' || items === null) throw new Error(`${at}: an array needs "items"`);
    return `Array<${typeOf(items as JsonSchema, resolveRef, at, indent)}>`;
  }
  if (typeof type === 'string') return primitive(type, at);
  throw new Error(`${at}: the schema has no type the generator recognises`);
}

function objectType(schema: JsonSchema, resolveRef: (ref: string) => string, at: string, indent: string): string {
  const properties = (schema['properties'] ?? {}) as Record<string, JsonSchema>;
  const required = new Set((schema['required'] ?? []) as string[]);
  const inner = `${indent}  `;
  const members: string[] = [];
  for (const [property, propertySchema] of Object.entries(properties)) {
    members.push(...comment(propertySchema['description'], inner));
    const optional = required.has(property) ? '' : '?';
    members.push(`${inner}${property}${optional}: ${typeOf(propertySchema, resolveRef, `${at}.${property}`, inner)};`);
  }
  return `{\n${members.join('\n')}\n${indent}}`;
}

function primitive(type: string, at: string): string {
  if (type === 'integer' || type === 'number') return 'number';
  if (type === 'string' || type === 'boolean' || type === 'null') return type;
  throw new Error(`${at}: unsupported type ${type}`);
}

function comment(description: unknown, indent: string): string[] {
  return typeof description === 'string' ? [`${indent}/** ${description} */`] : [];
}

if (import.meta.main) {
  writeFileSync(TYPES_FILE, generateTypes());
  console.log('Wrote schemas/query-engine.d.ts.');
}

// Throwaway databases for the test suite. scripts/test.ts builds them before the
// suite runs and passes their connection URLs to the test files in QUERY_ENGINE_TEST_*
// variables; test files call testEnvironment() to read them.

import { randomBytes } from 'node:crypto';
import pg from 'pg';

export interface TestEnvironment {
  /** Superuser on the test server's maintenance database. */
  serverAdminUrl: string;
  /** Superuser on the main test database (core layout, engine migrations, fixtures). */
  mainAdminUrl: string;
  /** The engine's login (granted query_engine_reader) on the main test database. */
  mainEngineUrl: string;
  /** A database with core's migrations only, used as a template for per-test copies. */
  coreTemplate: string;
  /** Every database this run creates starts with this prefix, so teardown can find it. */
  runId: string;
}

export const TEST_VARIABLES = {
  serverAdminUrl: 'QUERY_ENGINE_TEST_ADMIN_URL',
  mainAdminUrl: 'QUERY_ENGINE_TEST_MAIN_ADMIN_URL',
  mainEngineUrl: 'QUERY_ENGINE_TEST_MAIN_ENGINE_URL',
  coreTemplate: 'QUERY_ENGINE_TEST_CORE_TEMPLATE',
  runId: 'QUERY_ENGINE_TEST_RUN_ID',
} as const satisfies Record<keyof TestEnvironment, string>;

/** Reads the test databases. Throws, so the suite fails instead of skipping, when they are not set. */
export function testEnvironment(env: NodeJS.ProcessEnv = process.env): TestEnvironment {
  const missing = Object.values(TEST_VARIABLES).filter((name) => !env[name]);
  if (missing.length > 0) {
    throw new Error(
      `No test database is configured (${missing.join(', ')} not set). ` +
        'Run the suite with `npm test`, which builds the test database; see docs/testing.md.',
    );
  }
  const read = (name: string) => env[name] as string;
  return {
    serverAdminUrl: read(TEST_VARIABLES.serverAdminUrl),
    mainAdminUrl: read(TEST_VARIABLES.mainAdminUrl),
    mainEngineUrl: read(TEST_VARIABLES.mainEngineUrl),
    coreTemplate: read(TEST_VARIABLES.coreTemplate),
    runId: read(TEST_VARIABLES.runId),
  };
}

/** The same server and login as `url`, on another database. */
export function onDatabase(url: string, database: string): string {
  const copy = new URL(url);
  copy.pathname = `/${encodeURIComponent(database)}`;
  return copy.toString();
}

export async function withClient<T>(url: string, work: (client: pg.Client) => Promise<T>): Promise<T> {
  const client = new pg.Client({ connectionString: url });
  await client.connect();
  try {
    return await work(client);
  } finally {
    await client.end();
  }
}

export async function createDatabase(serverAdminUrl: string, name: string, template?: string): Promise<void> {
  // CREATE DATABASE takes no parameters; both names are generated by the test command.
  await withClient(serverAdminUrl, async (client) => {
    const from = template === undefined ? '' : ` TEMPLATE ${client.escapeIdentifier(template)}`;
    await client.query(`CREATE DATABASE ${client.escapeIdentifier(name)}${from}`);
  });
}

export async function dropDatabase(serverAdminUrl: string, name: string): Promise<void> {
  await withClient(serverAdminUrl, async (client) => {
    await client.query(`DROP DATABASE IF EXISTS ${client.escapeIdentifier(name)} WITH (FORCE)`);
  });
}

export interface DatabaseCopy {
  name: string;
  adminUrl: string;
  engineUrl: string;
  drop(): Promise<void>;
}

/** A fresh database with core's layout and nothing else: no engine migrations, no fixtures. */
export async function copyOfCoreDatabase(env: TestEnvironment): Promise<DatabaseCopy> {
  const name = `${env.runId}_copy_${randomBytes(3).toString('hex')}`;
  await createDatabase(env.serverAdminUrl, name, env.coreTemplate);
  return {
    name,
    adminUrl: onDatabase(env.mainAdminUrl, name),
    engineUrl: onDatabase(env.mainEngineUrl, name),
    drop: () => dropDatabase(env.serverAdminUrl, name),
  };
}
